// Lists the licence of every installed dependency and writes THIRD_PARTY_LICENSES.md.
// Run: npm run licenses. Flags anything that is not a common permissive licence for review.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const root = 'node_modules';
const rows = [];
const read = (dir) => {
  const f = join(dir, 'package.json');
  if (!existsSync(f)) return;
  const p = JSON.parse(readFileSync(f, 'utf8'));
  if (p.name) rows.push({ name: p.name, version: p.version ?? '', license: typeof p.license === 'string' ? p.license : p.license?.type ?? (p.licenses ? p.licenses.map((l) => l.type).join(' OR ') : 'UNKNOWN') });
};
for (const d of readdirSync(root)) {
  if (d.startsWith('.')) continue;
  if (d.startsWith('@')) for (const s of readdirSync(join(root, d))) read(join(root, d, s));
  else read(join(root, d));
}
rows.sort((a, b) => a.name.localeCompare(b.name));
const ok = /^(MIT|ISC|BSD-[23]-Clause|Apache-2\.0|0BSD|BlueOak-1\.0\.0|CC0-1\.0|Unlicense|Python-2\.0|CC-BY-4\.0|MPL-2\.0)$/;
const review = rows.filter((r) => !r.license.replace(/[()]/g, '').split(/ OR | AND /).some((l) => ok.test(l.trim())));
writeFileSync('THIRD_PARTY_LICENSES.md', `# Third-party licences\n\nGenerated by scripts/third-party-licenses.mjs. ${rows.length} packages.\n\n| Package | Version | Licence |\n| --- | --- | --- |\n${rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`).join('\n')}\n`);
console.log(`${rows.length} packages written to THIRD_PARTY_LICENSES.md`);
console.log(review.length ? `Check these by hand:\n${review.map((r) => `  ${r.name}@${r.version}: ${r.license}`).join('\n')}` : 'All licences are common permissive ones.');
